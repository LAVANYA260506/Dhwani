"""
Conversation model: the transcript of the conversation with Dhwani.

Each application has one conversation, stored as an ordered list of
messages. Messages cover what the applicant said or typed, what the
assistant replied, and the tool actions the agent took (for example filling
a field), so a session can be resumed and reviewed.

Transcripts contain personal data and are deleted with the application.
"""

import enum
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import JSON, Boolean, DateTime, Enum, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, backref, mapped_column, relationship

from app.core.database import Base
from app.models.application import Application  # noqa: F401  (registers the mapper)


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


class MessageRole(str, enum.Enum):
    APPLICANT = "applicant"
    ASSISTANT = "assistant"
    TOOL = "tool"  # a record of an action taken by the agent


class MessageChannel(str, enum.Enum):
    VOICE = "voice"
    TEXT = "text"
    SYSTEM = "system"  # generated by the app, for example a document result


class ConversationMessage(Base):
    __tablename__ = "conversation_messages"

    # Auto-increment ID doubles as the message order within the conversation
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    application_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("applications.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    role: Mapped[MessageRole] = mapped_column(
        Enum(MessageRole, native_enum=False, length=20), nullable=False
    )
    channel: Mapped[MessageChannel] = mapped_column(
        Enum(MessageChannel, native_enum=False, length=20),
        default=MessageChannel.TEXT,
        nullable=False,
    )
    language: Mapped[str] = mapped_column(String(5), default="en", nullable=False)

    # What was said or typed; for TOOL messages, a short description of the action
    content: Mapped[str] = mapped_column(Text, nullable=False)

    # The form field this message was about, if any
    field_id: Mapped[str | None] = mapped_column(String(80), nullable=True)

    # Only for TOOL messages: which tool ran, with what input and result
    tool_name: Mapped[str | None] = mapped_column(String(60), nullable=True)
    tool_input: Mapped[dict[str, Any] | None] = mapped_column(JSON, nullable=True)
    tool_result: Mapped[dict[str, Any] | None] = mapped_column(JSON, nullable=True)

    # True if the assistant's spoken reply was cut off by the applicant
    # (interruption handling, Phase 12)
    interrupted: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow, nullable=False
    )

    # Adds `application.messages` (in conversation order)
    application: Mapped["Application"] = relationship(
        "Application",
        backref=backref(
            "messages",
            cascade="all, delete-orphan",
            order_by="ConversationMessage.id",
        ),
    )

    def __repr__(self) -> str:
        return f"<ConversationMessage id={self.id} role={self.role.value}>"